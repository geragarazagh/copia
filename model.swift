// What one copy is: every item and every type the copying app wrote, kept as one entry (twelve files copied in Finder
// are one entry with twelve items, as Spotlight's own clipboard shows them, and go back as twelve).
import AppKit
import CryptoKit
import UniformTypeIdentifiers

enum Kind: String {
    case text, link, color, image, files, other
}

/// One type of one pasteboard item as read. Images are kept once, as PNG (a TIFF beside a PNG is the same picture;
/// a TIFF alone is converted losslessly), so `file` names a content-addressed file instead of holding the bytes.
struct Rep {
    var type: String
    var data: Data?
    var file: String?   // relative to the store folder: images/<sha256>.png or blobs/<sha256>
}

/// A pasteboard read, before it is stored.
struct Snapshot {
    var items: [[Rep]]
    var source: String?       // bundle id of the app that copied
    var concealed = false     // a password manager's copy: kept like any other (his word, 2026-11-14), only marked
}

/// One entry of the history, without its representations (those are read only for copying).
struct Entry: Equatable {
    var id: Int64 = 0
    var copied: Date
    var app: String?
    var kind: Kind
    var title: String         // what a row shows first: the text's start, the file's name, the link's title
    var text: String          // what search and the facts count: the whole plain text, or the file names
    var bytes: Int
    var count: Int            // pasteboard items (files in a Finder copy)
    var width = 0, height = 0 // a single image's pixels
    var thumb: String?        // images/<sha>.png of the first image, or the path of the first file
    var digest: String
    var deleted: Date?
    var concealed = false
    var url: String?          // a link's address when it is not the text itself (a link selected on a page)
    var picture: String?      // images/<sha>.<ext>: the page's picture a link carried (Safari's og:image)
    /// What makes two copies the same thing to a person (contentKey): the same text from Safari and from Notes, the
    /// same picture, the same files. Copied again, the entry moves to the top instead of making a twin.
    var key: String?

    /// A link's address: its own field, or the text that is the address.
    var address: String { url ?? text.trimmingCharacters(in: .whitespacesAndNewlines) }
    /// What search looks through: the title, the text and, for a link selected on a page, its address.
    func searchable(_ shown: String) -> String { shown + "\n" + text + (url.map { "\n" + $0 } ?? "") }
}

// MARK: pasteboard type names

extension NSPasteboard.PasteboardType {
    /// Inside every item this app writes (never a separate item: a lone marker item would be an extra paste).
    static let own = Self("com.geragaraza.copia.own")
    static let source = Self("org.nspasteboard.source")
    static let concealed = Self("org.nspasteboard.ConcealedType")
    static let transient = Self("org.nspasteboard.TransientType")
    static let autoGenerated = Self("org.nspasteboard.AutoGeneratedType")
    static let urlName = Self("public.url-name")
}

/// Writes no person made, by the nspasteboard.org convention and the older markers it lists (TextExpander and Butler,
/// TypeIt4Me, Typinator): text expanders and apps that put something on the pasteboard to do their own work and take
/// it back. They are not copies, so they never enter the history. Concealed (password managers) is a person's copy and
/// stays. Checked by ./test capture.
let skipMarkers: Set<String> = [
    "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
]

/// Types the system makes up by itself from the real ones (legacy aliases such as NSFilenamesPboardType, «Apple URL
/// pasteboard type», CorePasteboardFlavorType, dyn.*): storing them repeats the real type, and writing them back is
/// the system's job.
func isSynthesized(_ t: String) -> Bool {
    t.hasPrefix("dyn.") || t.contains(" ") || (t.hasPrefix("NS") && t.hasSuffix("PboardType")) || t == NSPasteboard.PasteboardType.own.rawValue
}

let imageTypes: Set<String> = [NSPasteboard.PasteboardType.png.rawValue, NSPasteboard.PasteboardType.tiff.rawValue]

// MARK: preparing a read for the store (off the main thread)

/// The stored form of a snapshot: images turned into PNG files named by their SHA-256 in `dir`, the entry's
/// display fields and the digest that finds the same copy again.
func prepare(_ s: Snapshot, dir: URL, at date: Date = Date()) -> (Entry, [[Rep]])? {
    var items: [[Rep]] = []
    var hasher = SHA256()
    var firstImage: String?, w = 0, h = 0, imageBytes = 0, images = 0
    for reps in s.items {
        var out: [Rep] = []
        let types = Set(reps.map(\.type))
        let isFile = types.contains(NSPasteboard.PasteboardType.fileURL.rawValue)
        // Image data of a file item is Finder's icon of the file, not the picture: it is kept as data like any type.
        if !isFile, let png = reps.first(where: { $0.type == NSPasteboard.PasteboardType.png.rawValue })?.data
            ?? reps.first(where: { $0.type == NSPasteboard.PasteboardType.tiff.rawValue })?.data.flatMap(pngData) {
            let name = "images/" + sha(png) + ".png"
            let url = dir.appendingPathComponent(name)
            if !FileManager.default.fileExists(atPath: url.path) { try? png.write(to: url, options: .atomic) }
            out.append(Rep(type: NSPasteboard.PasteboardType.png.rawValue, file: name))
            if firstImage == nil, let src = CGImageSourceCreateWithData(png as CFData, nil),
               let p = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any] {
                firstImage = name; w = p[kCGImagePropertyPixelWidth] as? Int ?? 0; h = p[kCGImagePropertyPixelHeight] as? Int ?? 0
            }
            imageBytes += png.count; images += 1
            for r in reps where !imageTypes.contains(r.type) { out.append(r) }
        } else {
            out = reps
        }
        out.sort { $0.type < $1.type }
        for r in out {
            hasher.update(data: Data(r.type.utf8))
            if let d = r.data { hasher.update(data: d) } else if let f = r.file { hasher.update(data: Data(f.utf8)) }
        }
        hasher.update(data: Data([0]))   // item boundary: [a][b] is not [ab]
        items.append(out)
    }
    // A big piece of data lives as a file beside the database, named by its content, so the database stays small
    // and two copies of the same data share one file.
    for i in items.indices { for j in items[i].indices {
        if let d = items[i][j].data, d.count > 256 * 1024 {
            let name = "blobs/" + sha(d)
            let url = dir.appendingPathComponent(name)
            if !FileManager.default.fileExists(atPath: url.path) { try? d.write(to: url, options: .atomic) }
            items[i][j] = Rep(type: items[i][j].type, file: name)
        }
    } }
    guard items.contains(where: { !$0.isEmpty }) else { return nil }

    let digest = hasher.finalize().map { String(format: "%02x", $0) }.joined()
    let key = contentKey(items) { r in r.data ?? r.file.flatMap { try? Data(contentsOf: dir.appendingPathComponent($0)) } }
    let strs = s.items.compactMap { item in item.first { $0.type == NSPasteboard.PasteboardType.string.rawValue }?.data
        .flatMap { String(data: $0, encoding: .utf8) } }
    let files = s.items.compactMap { item in item.first { $0.type == NSPasteboard.PasteboardType.fileURL.rawValue }?.data
        .flatMap { String(data: $0, encoding: .utf8) }.flatMap { URL(string: $0) } }
    var e = Entry(copied: date, app: s.source, kind: .other, title: "", text: "", bytes: 0, count: s.items.count,
                  digest: digest, concealed: s.concealed, key: key)
    if !files.isEmpty {
        e.kind = .files
        e.count = files.count
        e.text = files.map(\.lastPathComponent).joined(separator: "\n")
        e.title = files.count == 1 ? files[0].lastPathComponent : counted(files.count, "object|objects")
        e.bytes = files.reduce(0) { $0 + fileSize($1) }
        e.thumb = files[0].path
    } else if images > 0 {
        e.kind = .image
        e.title = images == 1 ? L("Image") : counted(images, "object|objects")
        e.text = strs.joined(separator: "\n")
        e.bytes = imageBytes
        e.width = images == 1 ? w : 0; e.height = images == 1 ? h : 0
        e.thumb = firstImage
    } else if !strs.isEmpty {
        let t = strs.joined(separator: "\n")
        e.text = t
        e.bytes = t.utf8.count
        let one = t.trimmingCharacters(in: .whitespacesAndNewlines)
        if isColor(one) {
            e.kind = .color; e.title = one.uppercased()
        } else if s.items.count == 1, let link = linkInfo(s.items[0], plain: t) {
            // The title and pictures only as the copying app gave them (link.swift); none given: the address.
            e.kind = .link
            e.title = link.title ?? link.url
            if link.url != one { e.url = link.url }
            e.thumb = link.icon.flatMap { keepPicture($0, dir: dir) }
            e.picture = link.image.flatMap { keepPicture($0, dir: dir) }
        } else {
            e.kind = .text
            e.title = headline(t)
        }
    } else {
        e.kind = .other
        e.title = L("Data")
        e.bytes = items.flatMap { $0 }.reduce(0) { $0 + ($1.data?.count ?? 0) }
    }
    return (e, items)
}

/// What a person would call the same copy, so copying it again moves it to the top (Maccy does the same with its
/// «supersedes»: the new copy's types all found in an old one). The digest alone was too strict: it hashes every type
/// the copying app wrote, so the same text from Safari (with HTML and RTF) and from Notes, or the same link copied twice
/// from Chrome (which writes a fresh source id each time), made twins. The key is the content a paste gives:
/// - files: their addresses, in order (twelve Finder files copied again are the same twelve);
/// - pictures (no files): their PNG files, already named by their SHA-256;
/// - text, links, colours: the plain text, hashed;
/// nil for anything else, which then matches by the digest as before.
func contentKey(_ items: [[Rep]], data: (Rep) -> Data?) -> String? {
    let furl = NSPasteboard.PasteboardType.fileURL.rawValue, png = NSPasteboard.PasteboardType.png.rawValue
    let plain = NSPasteboard.PasteboardType.string.rawValue
    let files = items.compactMap { $0.first { $0.type == furl }.flatMap(data).flatMap { String(data: $0, encoding: .utf8) } }
    if !files.isEmpty { return "f:" + sha(Data(files.joined(separator: "\n").utf8)) }
    let pics = items.compactMap { $0.first { $0.type == png }?.file }
    if !pics.isEmpty { return "i:" + pics.joined(separator: ",") }
    let texts = items.compactMap { $0.first { $0.type == plain }.flatMap(data).flatMap { String(data: $0, encoding: .utf8) } }
    if !texts.isEmpty { return "t:" + sha(Data(texts.joined(separator: "\n").utf8)) }
    return nil
}

/// The first 300 characters with line breaks and runs of spaces folded: enough for two lines of a row and never
/// a huge string in a text field (Maccy's popup slowed to a crawl on big clippings, issue #1080).
func headline(_ t: String) -> String {
    var out = "", space = false
    for ch in t {
        if ch.isWhitespace || ch.isNewline { space = !out.isEmpty; continue }
        if space { out.append(" "); space = false }
        out.append(ch)
        if out.count >= 300 { break }
    }
    return out
}

func isColor(_ s: String) -> Bool {
    guard s.hasPrefix("#"), s.count == 7 || s.count == 4 else { return false }
    return s.dropFirst().allSatisfy(\.isHexDigit)
}

func rgb(_ hex: String) -> (Int, Int, Int)? {
    var h = String(hex.dropFirst())
    if h.count == 3 { h = h.map { "\($0)\($0)" }.joined() }
    guard h.count == 6, let v = Int(h, radix: 16) else { return nil }
    return (v >> 16 & 255, v >> 8 & 255, v & 255)
}

func sha(_ d: Data) -> String { SHA256.hash(data: d).map { String(format: "%02x", $0) }.joined() }

/// A TIFF (or any image data ImageIO reads) as PNG, in one pass through ImageIO, keeping its colour profile.
func pngData(_ d: Data) -> Data? {
    guard let src = CGImageSourceCreateWithData(d as CFData, nil), CGImageSourceGetCount(src) > 0 else { return nil }
    let out = NSMutableData()
    guard let dst = CGImageDestinationCreateWithData(out, UTType.png.identifier as CFString, 1, nil) else { return nil }
    CGImageDestinationAddImageFromSource(dst, src, 0, nil)
    return CGImageDestinationFinalize(dst) ? out as Data : nil
}

func fileSize(_ u: URL) -> Int {
    guard let r = try? u.resourceValues(forKeys: [.isDirectoryKey, .totalFileAllocatedSizeKey, .fileSizeKey]) else { return 0 }
    if r.isDirectory == true {
        // A folder's size is its contents', as Finder's Get Info counts it.
        var n = 0
        let en = FileManager.default.enumerator(at: u, includingPropertiesForKeys: [.fileSizeKey], options: [], errorHandler: nil)
        while let f = en?.nextObject() as? URL { n += (try? f.resourceValues(forKeys: [.fileSizeKey]).fileSize) ?? 0 }
        return n
    }
    return r.fileSize ?? 0
}

// MARK: the facts line (objects · characters · words · ≈tokens · size)

/// Counted for language models: characters and words of the text, an estimate of tokens, the size.
/// Tokens: about 4 characters of Latin text and 2.8 of Cyrillic per token (measured on Claude's tokenizer for the
/// mockups); an image as Claude sees it: scaled to at most 1568 px on the long side and about 1.15 MP, then
/// width × height / 750 (a full-screen screenshot of a 16-inch MacBook Pro is about 1 530).
struct Facts {
    var head: String
    var parts: [String]

    init(_ entries: [Entry]) {
        let n = entries.count
        head = n == 1 ? kindLabel(entries[0]) : counted(n, "object|objects")
        let texts = entries.filter { $0.kind != .files && $0.kind != .image }.map(\.text)
        let ch = texts.reduce(0) { $0 + $1.count }
        let wd = texts.reduce(0) { $0 + wordCount($1) }
        var tk = texts.reduce(0.0) { $0 + tokenEstimate($1) }
        for e in entries where e.kind == .image && e.width > 0 { tk += imageTokens(e.width, e.height) }
        let b = entries.reduce(0) { $0 + $1.bytes }
        parts = []
        if ch > 0 { parts += [counted(ch, "character|characters"), counted(wd, "word|words")] }
        if tk >= 1 { parts.append("≈\u{00A0}" + counted(Int(tk.rounded()), "token|tokens")) }
        if b > 0 { parts.append(sizeText(b)) }
    }
}

/// The title a row or an icon shows. Words the app makes up itself («Image», «3 objects», «Data») are made in the
/// interface language when shown, not taken from the store, where they stay in the language of the day of the copy
/// (a test machine in English showed «2 objects» in a Russian panel, 2026-11-14).
func shownTitle(_ e: Entry) -> String {
    switch e.kind {
    case .image: return e.count == 1 ? L("Image") : counted(e.count, "object|objects")
    case .files where e.count > 1: return counted(e.count, "object|objects")
    case .other: return L("Data")
    default: return e.title
    }
}

func kindLabel(_ e: Entry) -> String {
    switch e.kind {
    case .text: L("Text")
    case .link: L("Link")
    case .color: L("Color")
    case .image: e.count == 1 ? L("Image") : counted(e.count, "object|objects")
    case .files: e.count == 1 ? L("File") : counted(e.count, "object|objects")
    case .other: L("Data")
    }
}

func wordCount(_ s: String) -> Int {
    var n = 0, inWord = false
    for ch in s {
        let w = ch.isLetter || ch.isNumber
        if w && !inWord { n += 1 }
        inWord = w || (inWord && (ch == "-" || ch == "'" || ch == "’"))
    }
    return n
}

func tokenEstimate(_ s: String) -> Double {
    var cyr = 0, other = 0
    for u in s.unicodeScalars {
        if (0x0400...0x04FF).contains(u.value) { cyr += 1 } else { other += 1 }
    }
    return Double(cyr) / 2.8 + Double(other) / 4
}

func imageTokens(_ w: Int, _ h: Int) -> Double {
    let a = Double(w * h)
    let s = min(1, 1568 / Double(max(w, h)), (1_150_000 / a).squareRoot())
    return (Double(w) * s) * (Double(h) * s) / 750
}
